import pytest

from xbsl_sonar import cli, data

HELP = Path(__file__).parent / "help"

ПДН = """
    ВидЭлемента: РегистрСведений
    Ид: 00000000-0000-4000-8000-000000000001
    Имя: ПерсДанные
    Измерения:
        -
            Имя: Участник
            Тип: Участники.Ссылка
    Ресурсы:
        -
            Имя: Телефон
            Тип: Строка
"""

ЖУРНАЛ = """
    @ВПроекте
    @НаСервере @ДоступноСКлиента
    статический метод ЗафиксироватьДоступ(Участник: Участники.Ссылка)
        Журнал.Записать(новый Журнал.Запись(Участник = Участник))
    ;
"""

ПАРАМЕТРЫ = ["--pd-entities", "ПерсДанные", "--pd-journal", "ЖурналДоступа.ЗафиксироватьДоступ",
             "--incident-sinks", "Обращения.ЗарегистрироватьОшибку"]


@pytest.fixture(scope="session")
def data_dir(tmp_path_factory) -> Path:
    return data.build(HELP, tmp_path_factory.mktemp("data"))


def check(tmp_path, monkeypatch, data_dir, files: dict[str, str],
          options: list[str] | None = None) -> list[tuple[str, int]]:
    files = {"ПерсДанные.yaml": ПДН, "ЖурналДоступа.xbsl": ЖУРНАЛ, **files}
    for name, code in files.items():
        path = tmp_path / "IT" / "Проект" / "Основное" / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(textwrap.dedent(code).lstrip(), encoding="utf-8")
    monkeypatch.chdir(tmp_path)
    cli.main(["check", "IT", "--data-dir", str(data_dir), "--rules", "ПР-07", "--json", "находки.json",
              *(ПАРАМЕТРЫ if options is None else options)])
    found = json.loads((tmp_path / "находки.json").read_text(encoding="utf-8"))["findings"]
    return [(Path(f["path"]).name, f["line"]) for f in found]


