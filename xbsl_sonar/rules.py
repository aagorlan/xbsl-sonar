def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def _element_span(lines: list[str], n: int, ind: int) -> tuple[int, int]:
    """Строки [начало, конец) отображения YAML, ключи которого стоят с отступом ind
    и которому принадлежит строка n."""
    start = n
    while start > 0 and (not lines[start - 1].strip() or _indent(lines[start - 1]) >= ind):
        start -= 1
    if start > 0 and lines[start - 1].lstrip().startswith("- ") and _indent(lines[start - 1]) == ind - 2:
        start -= 1
    end = n + 1
    while end < len(lines) and (not lines[end].strip() or (_indent(lines[end]) >= ind
                                and not (_indent(lines[end]) == ind - 2
                                         and lines[end].lstrip().startswith("-")))):
        end += 1
    return start, end


def _text_bodies(text: str, server: set[str] | None = None) -> dict[str, str]:
    """Методы модуля по строкам: имя → тело (от заголовка до следующего метода).
    В `server`, если передан, складываются серверные: `@НаСервере` без `@НаКлиенте`."""
    out: dict[str, list[str]] = {}
    current = None
    pending: set[str] = set()
    for line in text.splitlines():
        m = _TEXT_METHOD.match(line)
        if m:
            current = m.group(1)
            out[current] = []
            if server is not None and pending & _SERVER and not pending & _CLIENT:
                server.add(current)
            pending = set()
        elif line.lstrip().startswith("@"):
            pending |= set(re.findall(r"@(\w+)", line))
        elif current:
            out[current].append(line)
    return {k: "\n".join(v) for k, v in out.items()}


def _reaches_unguarded(name: str, bodies: dict[str, str], own: str, unguarded: frozenset[str],
                       server: set[str], seen: set[str]) -> str | None:
    """Метод с доступом с клиента без сверки, до которого доходит метод модуля `name`.
    Серверный метод — граница: дальше вызовы идут на сервере, и проверка в нём их покрывает."""
    if f"{own}.{name}" in unguarded:
        return f"{own}.{name}"
    if name in seen or name not in bodies:
        return None
    seen.add(name)
    for module, called in _TEXT_CALL.findall(bodies[name]):
        key = f"{module or own}.{called}"
        if key in unguarded:
            return key
        if not module and called in bodies and called not in server:
            found = _reaches_unguarded(called, bodies, own, unguarded, server, seen)
            if found:
                return found
    return None


def _read_pair(path, suffix: str) -> str | None:
    try:
        return path.with_name(path.name.split(".")[0] + suffix).read_text(encoding="utf-8-sig")
    except OSError:
        return None


_RIGHT_LINE = re.compile(r"^\s*(Изменение|ПоУмолчанию|Update|Default):\s*(\w+)\s*$", re.MULTILINE)
_ADMINS_ONLY = {"РазрешеноАдминистраторам", "AllowedToAdministrators"}


def _editable_by_others(yaml_text: str) -> bool:
    """Право изменения объекта указано и не ограничено администраторами: `Изменение`,
    а без него — `ПоУмолчанию`. Не указано вовсе — не знаем, считаем закрытым."""
    rights = dict(_RIGHT_LINE.findall(yaml_text))
    value = rights.get("Изменение") or rights.get("Update") or rights.get("ПоУмолчанию") \
        or rights.get("Default")
    return value is not None and value not in _ADMINS_ONLY


def _object_module(source: SourceFile) -> tuple[str, str] | None:
    """Модуль объекта формы (`Тип.Объект.xbsl`, `Тип.НаборЗаписей.xbsl`) рядом с формой
    или уровнем выше: (имя типа, текст), если объект вправе менять не только администратор
    (по `Тип.yaml` там же)."""
    m = _FORM_OF.search(source.text)
    if not m:
        return None
    for folder in (source.path.parent, source.path.parent.parent):
        for suffix in (".Объект.xbsl", ".НаборЗаписей.xbsl"):
            try:
                text = (folder / (m.group(1) + suffix)).read_text(encoding="utf-8-sig")
                described = (folder / (m.group(1) + ".yaml")).read_text(encoding="utf-8-sig")
            except OSError:
                continue
            return (m.group(1), text) if _editable_by_others(described) else None
    return None


def _field_checked(module: tuple[str, str], field: str, identity: set[str]) -> bool:
    """`ПередЗаписью` модуля объекта упоминает реквизит и сверяется с текущим пользователем."""
    own, text = module
    body = next((b for name, b in _text_bodies(text).items() if name in _BEFORE_WRITE), "")
    if not re.search(rf"(?<![\w]){re.escape(field)}(?![\w])", body):
        return False
    for q, name in _TEXT_CALL.findall(body):
        if name in _RIGHT_CHECK or f"{q or own}.{name}" in identity:
            return True
    return False


@rule("ПР-02", "Действие администратора без проверки на сервере", "S", severity=Severity.WARNING)
def admin_only_in_interface(source: SourceFile) -> Iterable[Diagnostic]:
    if source.kind != "yaml" or not _YAML_COMPONENT.search(source.text):
        return []
    lines = source.text.splitlines()
    switches = [(n, m) for n, line in enumerate(lines) if (m := _ADMIN_SWITCH.match(line))]
    if not switches:
        return []
    own = source.path.name.split(".")[0]
    unguarded = _unguarded_set()
    identity = set(filter(None, os.environ.get(IDENTITY_ENV, "").split(",")))
    pair = _read_pair(source.path, ".xbsl")
    server: set[str] = set()
    bodies = _text_bodies(pair, server) if pair is not None else {}
    module = None
    out: list[Diagnostic] = []
    reported: set[int] = set()
    for n, m in switches:
        ind = len(m.group(1)) + (2 if m.group(2) else 0)
        start, end = _element_span(lines, n, ind)
        names = [nm.group(1) for k in range(start, end)
                 if _indent(lines[k]) <= ind and (nm := _YAML_NAME.match(lines[k]))]
        key = f"{m.group(3)} {names[0] if names else own}"
        fields: list[tuple[int, str]] = []
        for k in range(start, end):
            if k in reported:
                continue
            h = _YAML_HANDLER.match(lines[k])
            if h:
                via = _reaches_unguarded(h.group(2), bodies, own, unguarded, server, set())
                if via:
                    reported.add(k)
                    out.append(Diagnostic(
                        source.rel, k + 1, _indent(lines[k]) + 1, "ПР-02", Severity.WARNING,
                        f"{key}: элемент виден только администратору, а {h.group(1)} "
                        f"{h.group(2)} доходит до '{via}' — метод с доступом с клиента пишет "
                        f"в повышенных правах без проверки текущего пользователя. Видимость решает "
                        f"клиент: проверить права в самом серверном методе.",
                    ))
                continue
            f = _YAML_FIELD.match(lines[k])
            if f:
                if module is None:
                    module = _object_module(source) or ("", "")
                if module[0] and not _field_checked(module, f.group(2), identity):
                    reported.add(k)
                    fields.append((k, f.group(2)))
        if fields:
            k = fields[0][0]
            names = ", ".join(name for _, name in fields)
            out.append(Diagnostic(
                source.rel, k + 1, _indent(lines[k]) + 1, "ПР-02", Severity.WARNING,
                f"{key}: {'поле' if len(fields) == 1 else 'поля'} {names} "
                f"{'видно' if len(fields) == 1 else 'видны'} только администратору, а "
                f"'{module[0]}.ПередЗаписью' не {'сверяет его' if len(fields) == 1 else 'сверяет их'} "
                f"с текущим пользователем — значение приходит из данных формы с клиента. "
                f"Проверить в ПередЗаписью, что {'его' if len(fields) == 1 else 'их'} меняет "
                f"администратор.",
            ))
    return out


# ПР-06: секрет строкой. Имя говорит о секрете — переменная, свойство, именованный
# аргумент, ключ соответствия; значение похоже на секрет — длинное, без пробелов,
# кириллицы и подстановок. Токен бота и заголовок авторизации ловятся по самому литералу.
_SECRET_NAME = re.compile(
    r"токен|пароль|секрет|ключapi|ключапи|приватныйключ|закрытыйключ"
    r"|token|passw|secret|apikey|api_key|privatekey|private_key", re.IGNORECASE)
_SECRET_SHAPED = re.compile(
    r"\d{8,10}:[A-Za-z0-9_-]{35}|(?:Bearer|Basic)\s+[A-Za-z0-9+/=._-]{16,}")
_YAML_DEFAULT = re.compile(r"^(\s*)(?:-\s+)?(ЗначениеПоУмолчанию|DefaultValue):\s*(.*?)\s*$")
_YAML_ITEM_KEY = re.compile(r"^(\s*)(?:-\s+)?(Имя|Name|Тип|Type):\s*(.*?)\s*$")
_APP_SECRET = re.compile(r"СекретПриложения|ApplicationSecret")


def _literal(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def _secret_like(value: str) -> bool:
    return (len(value) >= 8 and not re.search(r"[\sа-яА-ЯёЁ%]", value)
            and not value.startswith("="))


def _secret_in_yaml(source: SourceFile) -> list[Diagnostic]:
    out: list[Diagnostic] = []
    lines = source.text.splitlines()
    for n, line in enumerate(lines):
        m = _YAML_DEFAULT.match(line)
        if not m or not _secret_like(_literal(m.group(3))):
            continue
        ind = len(m.group(1))
        name, kind = "", ""
        for k in range(n - 1, -1, -1):
            if lines[k].strip() and _indent(lines[k]) < ind:
                break
            key = _YAML_ITEM_KEY.match(lines[k])
            if key and len(key.group(1)) + (2 if lines[k].lstrip().startswith("-") else 0) == ind:
                if key.group(2) in ("Имя", "Name"):
                    name = key.group(3)
                else:
                    kind = key.group(3)
        if _SECRET_NAME.search(name) or _APP_SECRET.search(kind):
            out.append(Diagnostic(
                source.rel, n + 1, ind + 1, "ПР-06", Severity.WARNING,
                f"Секрет {name or kind}: значение по умолчанию задано строкой в описании элемента — "
                f"оно уходит с исходниками. Задавать секрет в приложении, а не в YAML.",
            ))
    return out


@rule("ПР-06", "Секрет строкой в коде", "S", severity=Severity.WARNING)
def hardcoded_secret(source: SourceFile) -> Iterable[Diagnostic]:
    if source.kind == "yaml":
        return _secret_in_yaml(source)
    if source.kind != "xbsl":
        return []
    toks = code_tokens(source)
    out: list[Diagnostic] = []
    for i, t in enumerate(toks):
        if t.kind != "STRING":
            continue
        value = _literal(t.value)
        if _SECRET_SHAPED.search(value):
            out.append(Diagnostic(
                source.rel, t.line, t.col, "ПР-06", Severity.WARNING,
                "Секрет в строке: литерал похож на токен или заголовок авторизации — "
                "он уходит с исходниками. Хранить в СекретПриложения или в настройках.",
            ))
            continue
        follows = toks[i + 1].value if i + 1 < len(toks) else ""
        if not _secret_like(value) or follows in ("+", "."):
            continue
        prev = toks[i - 1] if i >= 1 else None
        holder = None
        if prev is not None and prev.kind == "OP" and prev.value == "=" and i >= 2 \
                and toks[i - 2].kind == "IDENT":
            holder = toks[i - 2].value
        elif prev is not None and prev.kind == "OP" and prev.value == "," and i >= 2 \
                and toks[i - 2].kind == "STRING" and i >= 3 and toks[i - 3].value == "(":
            holder = _literal(toks[i - 2].value)
        if holder and _SECRET_NAME.search(holder):
            out.append(Diagnostic(
                source.rel, t.line, t.col, "ПР-06", Severity.WARNING,
                f"Секрет {holder}: значение задано строкой в коде — оно уходит с исходниками "
                f"и меняется только сборкой. Хранить в СекретПриложения или в настройках "
                f"и читать на сервере.",
            ))
    return out


# ПР-07: журналирование ПДн. Первая половина — чтение ПДн человеком мимо журнала доступа:
# что считать ПДн и что журналом, знает только проект (`--pd-entities`, `--pd-journal`);
# без перечня ПДн половина не работает. Вторая — ПДн или секрет в тексте исключения
# (оно уходит в журнал событий) и в приёмниках обращений (`--incident-sinks`).
# Сущности ПДн с их измерениями: `Сущность:Изм1|Изм2,…` — собирает `check` по YAML проекта.
PD_ENTITIES_ENV = "XBSL_SONAR_PD_ENTITIES"
# Методы журнала доступа (`Модуль.Метод` через запятую) — параметр `--pd-journal`.
PD_JOURNAL_ENV = "XBSL_SONAR_PD_JOURNAL"
# Методы, которые пишут журнал сами или через вызываемые, — файл, его собирает `check`.
PD_JOURNALED_ENV = "XBSL_SONAR_PD_JOURNALED"
# Приёмники обращений (`Модуль.Метод` через запятую) — параметр `--incident-sinks`.
INCIDENT_SINKS_ENV = "XBSL_SONAR_INCIDENT_SINKS"

_PD_NAME = re.compile(
    r"почт|e_?mail|телефон|phone|фамили|отчеств|фио|логин|login|паспорт|passport",
    re.IGNORECASE)
_PD_EXACT = {"Адрес", "АдресПочты", "Address", "АдресЭлектроннойПочты"}
_PD_SUBSTITUTION = re.compile(r"%\{([^}]*)\}|%([^\W\d]\w*)")
_PD_IDENT = re.compile(r"[^\W\d]\w*")
_PD_LOADS = re.compile(r"\.\s*(?:ЗагрузитьЗапись|ЗагрузитьОбъект|Загрузить|LoadRecord|LoadObject|Load)\s*\(")
_PD_COUNT = re.compile(r"(?:КОЛИЧЕСТВО|COUNT)\s*\([^)]*\)", re.IGNORECASE)
_JOURNALED_SET: dict[str, frozenset[str]] = {}


def _pd_entities() -> dict[str, set[str]]:
    out: dict[str, set[str]] = {}
    for item in filter(None, os.environ.get(PD_ENTITIES_ENV, "").split(",")):
        name, _, dims = item.partition(":")
        out[name] = set(filter(None, dims.split("|")))
    return out


def _journaled() -> frozenset[str]:
    path = os.environ.get(PD_JOURNALED_ENV, "")
    if path not in _JOURNALED_SET:
        try:
            with open(path, encoding="utf-8") as f:
                _JOURNALED_SET[path] = frozenset(filter(None, f.read().splitlines()))
        except OSError:
            _JOURNALED_SET[path] = frozenset()
    journal = set(filter(None, os.environ.get(PD_JOURNAL_ENV, "").split(",")))
    return _JOURNALED_SET[path] | journal


def _pd_sensitive(expr: str) -> str | None:
    """Имя ПДн или секрета в выражении подстановки; `Представление()` ссылки — не ПДн."""
    if "Представление" in expr or "Presentation" in expr:
        return None
    for name in _PD_IDENT.findall(expr):
        if name in _PD_EXACT or _PD_NAME.search(name) or _SECRET_NAME.search(name):
            return name
    return None


def _query_reads(body: str, entities: dict[str, set[str]]) -> str | None:
    """Сущность ПДн, поле которой (кроме измерений) запрос выводит в выборку."""
    for m in re.finditer(r"(?:ИЗ|FROM)\s+(\w+)(?:\s+(?:КАК|AS)\s+(\w+))?", body):
        entity = m.group(1)
        if entity not in entities:
            continue
        start = max(body.rfind("ВЫБРАТЬ", 0, m.start()), body.rfind("SELECT", 0, m.start()))
        if start < 0:
            continue
        selection = _PD_COUNT.sub("", body[start:m.start()])
        aliases = {entity, m.group(2) or entity}
        for alias, field in re.findall(r"(\w+)\.(\w+)", selection):
            if alias in aliases and field not in entities[entity]:
                return entity
    return None


def _calls_any(text: str, own: str, keys: frozenset[str]) -> bool:
    return any(f"{q or own}.{name}" in keys for q, name in _TEXT_CALL.findall(text))


def _pd_reads_xbsl(source: SourceFile, entities: dict[str, set[str]]) -> list[Diagnostic]:
    own = source.path.name.split(".")[0]
    identity = frozenset(filter(None, os.environ.get(IDENTITY_ENV, "").split(",")))
    journaled = _journaled()
    out: list[Diagnostic] = []
    methods: list[tuple[str, int, set[str], list[str]]] = []
    pending: set[str] = set()
    for n, line in enumerate(source.text.splitlines(), 1):
        m = _TEXT_METHOD.match(line)
        if m:
            methods.append((m.group(1), n, pending, []))
            pending = set()
        elif line.lstrip().startswith("@"):
            pending |= set(re.findall(r"@(\w+)", line))
        elif methods:
            methods[-1][3].append(line)
    for name, line, ann, lines in methods:
        if not (ann & _SERVER and ann & _FROM_CLIENT):
            continue
        body = "\n".join(lines)
        entity = None
        for candidate in entities:
            for stmt in re.split(r";|\n\s*\n", body):
                if re.search(rf"(?<![\w.]){candidate}\s*\.", stmt) and _PD_LOADS.search(stmt):
                    entity = candidate
                    break
            if entity:
                break
        entity = entity or _query_reads(body, entities)
        if entity is None:
            continue
        if (_calls_any(body, own, journaled) or _calls_any(body, own, identity)
                or re.search(r"(?<![\w])(?:ТекущийПользователь|CurrentUser|ПроверитьПраво|ЕстьПраво"
                             r"|CheckRight|HasRight)\b", body)):
            continue
        out.append(Diagnostic(
            source.rel, line, 1, "ПР-07", Severity.WARNING,
            f"Метод '{name}' доступен с клиента и читает персональные данные ({entity}) "
            f"без записи в журнал доступа и без сверки с текущим пользователем: чужие ПДн "
            f"уйдут человеку незаметно. Записать доступ в журнал или сверить, что читается своё.",
        ))
    return out


_PD_YAML_FORM = re.compile(r"^\s*(?:-\s+)?(?:Тип|Type):\s*(?:ФормаЗаписи|ФормаОбъекта|RecordForm|ObjectForm)"
                        r"<\s*(\w+)\s*\.", re.MULTILINE)
_PD_YAML_TABLE = re.compile(r"^\s*(?:-\s+)?(?:Таблица|Table):\s*(\w+)\s*$", re.MULTILINE)
_PD_YAML_FIELD = re.compile(r"^\s*(?:-\s+)?(?:Выражение|Expression):\s*(\S+)\s*$", re.MULTILINE)


def _pd_reads_yaml(source: SourceFile, entities: dict[str, set[str]]) -> list[Diagnostic]:
    text = source.text
    found: tuple[str, int] | None = None
    for m in _PD_YAML_FORM.finditer(text):
        if m.group(1) in entities:
            found = (m.group(1), text.count("\n", 0, m.start()) + 1)
            break
    if found is None:
        for m in _PD_YAML_TABLE.finditer(text):
            entity = m.group(1)
            if entity not in entities:
                continue
            fields = [f.group(1).split(".")[0] for f in _PD_YAML_FIELD.finditer(text, m.end())]
            if any(f not in entities[entity] for f in fields):
                found = (entity, text.count("\n", 0, m.start()) + 1)
                break
    if found is None:
        return []
    pair = _read_pair(source.path, ".xbsl") or ""
    if _calls_any(pair, source.path.name.split(".")[0], _journaled()):
        return []
    return [Diagnostic(
        source.rel, found[1], 1, "ПР-07", Severity.WARNING,
        f"Форма показывает персональные данные ({found[0]}) без записи в журнал доступа: "
        f"модуль формы журнал не зовёт. Записать доступ при чтении (ПослеЧтения) "
        f"или не выводить поля ПДн.",
    )]


def _sink_args(toks: list) -> list[tuple[int, int, str]]:
    """Аргументы исключений и приёмников обращений: (начало, конец, что) — индексы токенов."""
    sinks = set(filter(None, os.environ.get(INCIDENT_SINKS_ENV, "").split(",")))
    sink_names = {s.split(".")[-1]: s for s in sinks}
    out = []
    for i, t in enumerate(toks):
        start = None
        what = ""
        if t.kind == "KEYWORD" and t.canonical == "THROW":
            k = i + 1
            while k < len(toks) and toks[k].value != "(" and toks[k].line - t.line < 3:
                k += 1
            if k < len(toks) and toks[k].value == "(":
                start, what = k, "текст исключения"
        elif (t.kind == "IDENT" and t.value in sink_names and i + 1 < len(toks)
              and toks[i + 1].value == "("):
            module = sink_names[t.value].rsplit(".", 1)[0] if "." in sink_names[t.value] else ""
            if not module or (i >= 2 and toks[i - 1].value == "." and toks[i - 2].value == module):
                start, what = i + 1, f"обращение ({t.value})"
        if start is None:
            continue
        depth, k = 0, start
        while k < len(toks):
            if toks[k].value == "(":
                depth += 1
            elif toks[k].value == ")":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        out.append((start, k, what))
    return out


def _pd_in_log(source: SourceFile) -> list[Diagnostic]:
    toks = code_tokens(source)
    out: list[Diagnostic] = []
    for start, end, what in _sink_args(toks):
        for k in range(start + 1, end):
            t = toks[k]
            name = None
            if t.kind == "STRING":
                for braced, bare in _PD_SUBSTITUTION.findall(t.value):
                    name = _pd_sensitive(braced or bare)
                    if name:
                        break
            elif t.kind == "IDENT" and toks[k - 1].value == "+":
                chain = [t.value]
                j = k + 1
                while j + 1 < end and toks[j].value == "." and toks[j + 1].kind == "IDENT":
                    chain.append(toks[j + 1].value)
                    j += 2
                name = _pd_sensitive(".".join(chain))
            if name:
                out.append(Diagnostic(
                    source.rel, t.line, t.col, "ПР-07", Severity.WARNING,
                    f"{name}: персональные данные или секрет попадают в {what} — оттуда "
                    f"в журнал событий и обращения в поддержку, которые читают администраторы. "
                    f"Писать в сообщение ссылку или код, а не само значение.",
                ))
                break
    return out


@rule("ПР-07", "Персональные данные мимо журнала доступа или в журнале событий", "S",
      severity=Severity.WARNING)
def pd_logging(source: SourceFile) -> Iterable[Diagnostic]:
    entities = _pd_entities()
    if source.kind == "yaml":
        return _pd_reads_yaml(source, entities) if entities else []
    if source.kind != "xbsl":
        return []
    out = _pd_reads_xbsl(source, entities) if entities else []
    return out + _pd_in_log(source)


