def _form_uploads(source: SourceFile) -> list[Diagnostic]:
    found = list(_FORM_UPLOAD.finditer(source.text))
    if not found:
        return []
    described = _read_pair(source.path, ".yaml") or ""
    form = _FORM_OF.search(described)
    module = ""
    if form:
        for folder in (source.path.parent, source.path.parent.parent):
            try:
                module = (folder / (form.group(1) + ".Объект.xbsl")).read_text(encoding="utf-8-sig")
                break
            except OSError:
                continue
    before = next((b for name, b in _text_bodies(module).items() if name in _BEFORE_WRITE), "")
    out = []
    for m in found:
        field = m.group(1)
        if re.search(rf"(?<![\w]){re.escape(field)}(?![\w])", before):
            continue
        out.append(Diagnostic(
            source.rel, source.text.count("\n", 0, m.start()) + 1, 1, "ПР-08", Severity.WARNING,
            f"Загруженный файл уходит в реквизит '{field}' записью формы без проверки размера "
            f"и типа на сервере: фильтр диалога выбора обходится. Проверить файл в ПередЗаписью "
            f"модуля объекта или принимать его серверным методом с проверкой.",
        ))
    return out


@rule("ПР-08", "Загрузка файла без проверки размера и типа", "S", severity=Severity.WARNING)
def file_upload(source: SourceFile) -> Iterable[Diagnostic]:
    if source.kind != "xbsl":
        return []
    own = source.path.name.split(".")[0]
    admins = _key_set(ADMIN_ENV)
    uploads = _key_set(UPLOAD_ENV)
    out: list[Diagnostic] = []
    for name, line, ann, header, lines in _methods_with_headers(source.text):
        body = "\n".join(lines)
        source_kind = None
        if ann & _SERVER and ann & _FROM_CLIENT and f"{own}.{name}" in uploads:
            used = [p for p in _FILE_PARAM.findall(header)
                    if re.search(rf"(?<![\w.]){re.escape(p)}(?![\w])", body)]
            if used:
                source_kind = f"параметр {', '.join(used)} приходит с клиента"
        if source_kind is None and _HTTP_PARAM.search(header) and _BODY_BYTES.search(body):
            source_kind = "тело HTTP-запроса читается целиком"
        if (source_kind is None or not _STORE_OR_PARSE.search(body)
                or _guarded_by_admin(lines, own, admins)):
            continue
        sized, typed = _upload_checks(lines)
        if sized and typed:
            continue
        out.append(Diagnostic(
            source.rel, line, 1, "ПР-08", Severity.WARNING,
            f"Метод '{name}' принимает файл ({source_kind}) без проверки {_missing(sized, typed)} "
            f"на сервере: ограничения диалога выбора файла обходятся прямым вызовом. Сравнить "
            f"размер с пределом и проверить тип до сохранения или разбора.",
        ))
    return out + _form_uploads(source)


def _entry_map(env: str) -> dict[str, str]:
    """`Модуль.Метод:строка` → пояснение из файла, путь к которому — в переменной окружения env."""
    out: dict[str, str] = {}
    for line in _key_set(env):
        key, _, why = line.partition("\t")
        out[key] = why
    return out


@rule("ПР-09", "Граница работы из значения извне без предела", "S", severity=Severity.WARNING)
def unbounded_input(source: SourceFile) -> Iterable[Diagnostic]:
    if source.kind != "xbsl":
        return []
    own = source.path.name.split(".")[0]
    entries = _entry_map(UNBOUNDED_ENV)
    out: list[Diagnostic] = []
    for name, line, _ann, _header, _lines in _methods_with_headers(source.text):
        why = entries.get(f"{own}.{name}:{line}")
        if why is None:
            continue
        out.append(Diagnostic(
            source.rel, line, 1, "ПР-09", Severity.WARNING,
            f"Метод '{name}': {why} — без предела. Один вызов со списком любой длины даёт "
            f"столько же обращений к данным. Сравнить размер с пределом и отказать до цикла "
            f"или собрать значения в один запрос.",
        ))
    return out


# ПР-10: блок `поймать`, в котором с ошибкой ничего не сделано.
_BARE = {"RETURN", "CONTINUE", "BREAK"}


def _comment_between(text: str, first: int, last: int) -> bool:
    """Есть ли строка-комментарий среди строк first..last (нумерация с 1)."""
    lines = text.split("\n")
    return any(line.lstrip().startswith("//") for line in lines[first - 1:last])


@rule("ПР-10", "Ошибка поймана и отпущена молча", "D", severity=Severity.WARNING)
def swallowed_exception(source: SourceFile) -> Iterable[Diagnostic]:
    if source.kind != "xbsl":
        return []
    toks = code_tokens(source)
    out: list[Diagnostic] = []

    def close(c: int, end: int) -> None:
        """Тело `поймать` с токена c до токена end (следующий `поймать`, `вконце` или `;`)."""
        body = [b for b in toks[c + 1:end] if b.line > toks[c].line]
        if not all(b.kind == "KEYWORD" and b.canonical in _BARE for b in body):
            return
        if _comment_between(source.text, toks[c].line + 1, toks[end].line - 1):
            return
        out.append(Diagnostic(
            source.rel, toks[c].line, toks[c].col, "ПР-10", Severity.WARNING,
            "Ошибка поймана и отпущена молча: в блоке 'поймать' с ней ничего не сделано. "
            "Записать в журнал событий или передать дальше; если отпустить правильно – "
            "объяснить комментарием в теле блока.",
        ))

    depth = 0  # глубина блоков: `поймать` относится к `попытка` той же глубины
    tries: list[int] = []  # глубины открытых `попытка`
    pending: dict[int, int] = {}  # глубина попытки -> индекс её последнего `поймать`
    prev = None
    for i, t in enumerate(toks):
        at_try = bool(tries) and tries[-1] == depth
        if t.kind == "KEYWORD" and t.canonical in _OPENERS and t.value[:1].islower():
            is_else_if = (t.canonical == "IF" and prev is not None and prev.kind == "KEYWORD"
                          and prev.canonical == "ELSE" and prev.line == t.line)
            is_abstract = (t.canonical == "METHOD" and prev is not None and prev.kind == "KEYWORD"
                           and prev.canonical == "ABSTRACT")
            if not is_else_if and not is_abstract:
                depth += 1
                if t.canonical == "TRY":
                    tries.append(depth)
        elif t.kind == "KEYWORD" and t.canonical in ("CATCH", "FINALLY") and at_try:
            c = pending.pop(depth, None)
            if c is not None:
                close(c, i)
            if t.canonical == "CATCH":
                pending[depth] = i
        elif t.kind == "OP" and t.value == ";":
            if at_try:
                tries.pop()
                c = pending.pop(depth, None)
                if c is not None:
                    close(c, i)
            depth = max(depth - 1, 0)
        prev = t
    return out
